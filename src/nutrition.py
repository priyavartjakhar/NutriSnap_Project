def get_nutrition(class_name):
    """Return nutritional data dict for a given Food-101 class name.

    Args:
        class_name: Food-101 class name (e.g. 'apple_pie').

    Returns:
        Dict with keys: calories, protein, fat, carbs, fiber, serving_size.
        Returns None if class_name is not found.
    """
    return NUTRITION_DATA.get(class_name, None)


def get_display_name(class_name):
    """Convert a Food-101 class name to a human-readable title.

    Args:
        class_name: Food-101 class name (e.g. 'apple_pie').

    Returns:
        Title-cased display name (e.g. 'Apple Pie').
    """
    return class_name.replace("_", " ").title()
